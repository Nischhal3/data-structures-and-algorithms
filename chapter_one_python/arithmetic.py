
# Exercise: Arithmetic
#
# Write a program that takes two integers, a and b, as input.
# Display their sum, difference, product, quotient, remainder,
# and the result of raising a to the power of b.

a = int(input())
b = int(input())

print(f"{a} + {b} is {a + b}")
print(f"{a} - {b} is {a - b}")
print(f"{a} * {b} is {a * b}")
print(f"{a} / {b} is {a / b}")
print(f"{a} % {b} is {a % b}")
print(f"{a} ^ {b} is {a ** b}")